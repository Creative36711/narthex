def npc(nid, label, desc, **kw):
    e = {"id": nid, "type": "npc", "label": label, "description": desc,
         "portrait": {"neutral": kw.pop("portrait", "")},
         "stats": kw.pop("stats"), "skills": kw.pop("skills")}
    e.update(kw)
    return e


def item(iid, label, desc, category, weight=0.5, stackable=True, **kw):
    e = {"id": iid, "type": "item", "category": category, "label": label, "description": desc,
         "weight": weight, "stackable": stackable}
    e.update(kw)
    return e


def _mech_check(difficulty, success, fail, skill="mechanics"):
    return {"type": "skill_check_gate", "skill": skill, "difficulty": difficulty,
            "success_effects": success, "fail_effects": fail}


def _spot_check(difficulty, success, fail):
    return {"type": "skill_check_gate", "skill": "spot", "difficulty": difficulty,
            "success_effects": success, "fail_effects": fail}


