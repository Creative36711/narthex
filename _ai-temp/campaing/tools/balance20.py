"""Ход 20: разбор полётов по выживанию и деньги.

Что показала проверка:

**Еда, вода и тепло были декорацией.** Смета добросовестного прохода —
52 часа. При расходе 0,9/ч голод тратил за проход 47 из 100, жажда — 57,
тепло — 62: ни одна потребность не спускалась даже в красную зону, ни один
паёк не был нужен. Суточный слой кампании ничего не стоил игроку, хотя на
него навешаны статусы, правила нуля, торговцы и рецепты.

Стало: голод 1,3/ч, жажда 1,4/ч, тепло 1,5/ч, сон 1,0/ч. Разбор по сметам:

| проход        | часов | голод | жажда | тепло | сон  | что надо сделать            |
|---------------|-------|-------|-------|-------|------|-----------------------------|
| критический   | 36    | 47    | 50    | 54    | 36   | ничего — скорость награждена |
| добросовестный| 52    | 68    | 73    | 78    | 52   | похлёбка, вода, жаровня     |
| полный        | 78    | 101   | 109   | 117   | 78   | есть, пить и греться часов на десять — и срок всё равно выйдет |

То есть: кто бежит — тот не ест; кто копает всё — тот платит часами,
которых у него нет. Именно это и было задумано, но цифры этого не делали.

**Деньги.** Игрок получает за проход около 47 марок (20 со старта, 20 за
клапан, 7 из кармана стража) плюс продажа лома. Дыхатель у Дожа стоит 34,
но его можно собрать на верстаке из тряпья, лома и ключа — ключ лежит на
приводе, тряпьё и лом находятся в ящике. Оба пути проверены: нужное есть
в мире, а не только в кошельке.

**Опыт.** На мирный проход приходится 566 опыта из 631, на бой — 65.
Мирный не беднее боевого, как и обещано в документе.

Скрипт идемпотентен.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

DECAY = {
    'need_hunger': 1.3,
    'need_thirst': 1.4,
    'need_warmth': 1.5,
    'need_rest': 1.0,
}
ROUTES = {'критический': 36, 'добросовестный': 52, 'полный': 78}


def load(rel):
    with open(os.path.join(ROOT, rel), encoding='utf-8') as f:
        return json.load(f)


def save(rel, data):
    with open(os.path.join(ROOT, rel), 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')


def main():
    camp = load('campaign.json')
    was = {}
    for need in camp['needs']:
        if need['id'] in DECAY:
            was[need['id']] = need['decay_per_tick']
            need['decay_per_tick'] = DECAY[need['id']]

    # Удушье было смертным приговором: у дознавателя около 10 здоровья,
    # а статус снимал по 2 в час восемь часов подряд плюс 3 сразу — то есть
    # минус 19 при десяти. Ошибка в расчёте воздуха стоила жизни всегда, без
    # шанса выбраться. Теперь −1 сразу и −1 в час: герой выходит наверх на
    # последнем здоровье и с −15 к следствию и вниманию, но живой.
    st = camp['statuses'][[s['id'] for s in camp['statuses']].index('status_choke')]
    was_choke = (st.get('dot') or {}).get('hp')
    st['dot'] = {'hp': 1}
    st['description'] = ('Воздух кончился. Пальцы синеют, мысли цепляются за пол: '
                         'на последнем здоровье надо не искать, а подниматься.')
    save('campaign.json', camp)

    rule = load('rules/rule_zero_air.json')
    for e in rule['effects']:
        if e.get('type') == 'change_hp':
            e['delta'] = -1
    save('rules/rule_zero_air.json', rule)

    print('БАЛАНС 20')
    for nid, new in DECAY.items():
        print('  %s: %.1f → %.1f/ч' % (nid, was[nid], new))
    print()
    print('  %-15s %6s %7s %7s %7s %7s' % ('проход', 'часов', 'голод', 'жажда', 'тепло', 'сон'))
    for name, hours in ROUTES.items():
        row = [round(hours * v) for v in (DECAY['need_hunger'], DECAY['need_thirst'],
                                          DECAY['need_warmth'], DECAY['need_rest'])]
        print('  %-15s %6d %7d %7d %7d %7d' % (name, hours, *row))
    print()
    print('  шкала 100, красная зона: голод и жажда 20, тепло 25, сон 20, воздух 25')
    print('  удушье: было −3 сразу и −2/ч восемь часов (минус 19 при 10 здоровья) '
          '— теперь −1 сразу и −1/ч: шанс выбраться есть')


if __name__ == '__main__':
    main()
