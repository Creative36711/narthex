import type { SoundHookMap } from './audio'


import type { CampaignMeta } from './campaign'


export interface TimeOfDayThresholds {
  /** час начала каждого периода (в тиках от начала суток) */
  morning: number
  day: number
  evening: number
  night: number
}

export interface FactionDef {
  id: string
  label: string
  base_disposition: number
  /** краткая справка о фракции */
  description?: string
  /** служебная фракция: отношение не меняется, игроку не показывается */
  hidden?: boolean
}

/** Категория предметов: задаёт, какие свойства доступны предмету (фидбек №8). */
export interface ItemCategoryDef {
  id: string
  label: string
  /** предметы категории можно использовать для восстановления здоровья */
  restores_hp?: boolean
  /** какие потребности восстанавливают предметы категории (id из реестра needs) */
  restores_needs?: string[]
  /** предметы категории — оружие (навык, урон и т.д.) */
  is_weapon?: boolean
  /** предметы категории — броня (очки поглощения урона) */
  is_armor?: boolean
  /** звуки взаимодействий категории предметов (хук → id звука) */
  sounds?: SoundHookMap
}

/**
 * Профиль механик кампании (блок 1 ТЗ «Гибкий движок»). Каждое поле —
 * выключатель подсистемы; ОТСУТСТВУЮЩЕЕ поле (или весь `features`) означает,
 * что механика ВКЛЮЧЕНА — старые кампании работают без изменений.
 * Тумблеры скрывают подсистему и в движке, и в интерфейсе игрока.
 */
export interface CampaignFeatures {
  /** карта мира и путешествия между локациями */
  map?: boolean
  /** инвентарь, экипировка, предметы в бою (эффекты предметов продолжают работать) */
  inventory?: boolean
  /** потребности и их убывание/восстановление */
  needs?: boolean
  /** навыки: проверки резолвятся успехом без броска, рост отключён */
  skills?: boolean
  /** панель отношений (сами отношения продолжают меняться — могут гейтить диалоги) */
  relationships?: boolean
  /** торговля */
  trade?: boolean
  /** тактический бой: конфликты резолвятся немедленной победой */
  combat?: boolean
  /** отображение часов и времени суток (ход времени остаётся) */
  time?: boolean
}

/** Совместимый путь: единственная реализация флагов находится в core/caps. */
/** Эффективный стартовый тик забега: единая точка (движок, HUD-дедлайн и
 *  условие elapsed_ge), чтобы «умолчание» не разъезжалось. Историческое
 *  умолчание движка — 8 (утро первого дня). */
export function startTick(meta: CampaignMeta): number {
  return meta.starting_tick ?? 8
}

/**
 * Шрифт кампании (блок 2 ТЗ «Гибкий движок»): файл пакета (обычно
 * `assets/fonts/…`) или внешняя ссылка. Подключается `@font-face` на лету.
 */
export interface FontDef {
  id: string
  label: string
  src: string // .woff2/.woff/.ttf/.otf
  /** начертание для @font-face (например '400', '700'); по умолчанию '400' */
  weight?: string
  style?: 'normal' | 'italic'
  /** визуальная поправка размера для конкретного шрифта (0.8 .. 1.3, по умолчанию 1) */
  size_adjust?: number
}

/**
 * Игровой визуальный профиль (редизайн 2026): «стартовый художественный набор»,
 * а не тип механики. Профиль задаёт палитру, типографику, формы, стиль панелей
 * и именованный атмосферный эффект; поверх него автор допустимо
 * переопределяет акцент, шрифтовые роли, фоны и атмосферу (см. ThemeDoc).
 * Меняет только оформление — ни правил, ни dice_rules, ни данных.
 */
export type VisualProfileId =
  | 'forge'
  | 'epic-fantasy'
  | 'dark-fantasy'
  | 'myth-folklore'
  | 'gothic-horror'
  | 'cosmic-horror'
  | 'noir'
  | 'historical'
  | 'wilderness'
  | 'postapocalypse'
  | 'scifi'
  | 'cyberpunk'
  | 'modern'

/**
 * Тема оформления кампании (блок 2 ТЗ). Применяется ТОЛЬКО к Player Mode;
 * редактор остаётся в фирменном стиле. Палитра переопределяется ограниченно:
 * акцент и несколько тонов поверхностей; движок подбирает читаемые текстовые роли.
 */
export interface ThemeDoc {
  /**
   * визуальный профиль игры: «Фэнтези» / «Хоррор» / «Выживание».
   * Не задан — «Фэнтези» (наследие темы «Пепла Каэрдена»).
   * Старые кампании без этого поля открываются без изменений.
   */
  profile?: VisualProfileId
  /**
   * атмосферный эффект профиля (виньетка/зерно/чистый кадр).
   * Не задан или true — эффект профиля включён; false — чистый кадр.
   */
  atmosphere?: boolean
  /** роли шрифтов — id из `meta.fonts`; отсутствует роль — системный шрифт */
  fonts?: {
    /** основной текст: диалоги, панели, кнопки */
    body?: string
    /** заголовки: названия сцен и панелей, меню */
    display?: string
    /** «рукописный»: журнал, записки, кодекс */
    hand?: string
  }
  /** общий множитель размера шрифта игры (0.8 .. 1.4, по умолчанию 1) */
  font_scale?: number
  /** точные размеры шрифтов в пикселях */
  font_sizes?: {
    /** основной текст: описания, сообщения (по умолчанию 15) */
    body?: number
    /** заголовки: названия локаций, сцен, панелей (по умолчанию 20) */
    display?: number
    /** реплики и варианты ответов в диалогах (по умолчанию 16) */
    dialogue?: number
    /** кнопки, списки, мелкие элементы интерфейса (по умолчанию 13) */
    ui?: number
  }
  /** межстрочный интервал (множитель 1.2 .. 2.0, по умолчанию 1.5) */
  line_height?: number
  /** межбуквенное расстояние (в em, например 0.01em..0.05em) */
  letter_spacing?: string
  menu?: {
    /** фон главного меню (файл пакета или ссылка) */
    background?: string
    /** затемнение фона 0…0.9 для читаемости текста (по умолчанию 0.5) */
    dim?: number
    /** медленный зум фона («кен-бёрнс») */
    ken_burns?: boolean
    /** арт/лого кампании над заголовком. ОБЯЗАТЕЛЬНО прозрачный фон (PNG с
     *  альфой): арт лежит поверх фона меню, с фоном выглядит чёрным квадратом. */
    title_art?: string
  }
  /** фон экрана финала; нет — используется фон меню */
  end?: { background?: string }
  /** акцентный цвет интерфейса (заменяет золото темы) */
  accent?: string
  /**
   * Тоны поверхностей (мастерская докрутка палитры): панели, карточки/кнопки,
   * колодцы, фон строк журнала. HEX (#rrggbb). Пусто — тон профиля.
   */
  tokens?: {
    /** фон панелей и шапок (панель, колодцы диалогов) */
    panel?: string
    /** карточки, кнопки, ячейки статов, чипы */
    cards?: string
    /** углубления (поля ввода, прогресс-полосы) */
    inset?: string
    /** фон списка журнала событий */
    log?: string
  }
  /** рамка-«кадр» вокруг панелей: изображение 9-срез (border-image) */
  frame?: {
    /** файл пакета или ссылка (PNG с прозрачной сердцевиной, орнамент по краям) */
    image?: string
    /** толщина среза рамки в px (умолчание 30) */
    slice?: number
    /** видимая толщина рамки в px (умолчание 20) */
    width?: number
  }  /**
   * Полный CSS мастера (продвинутое оформление; готовится как отдельная опция
   * — сейчас доступна всем). Применяется ТОЛЬКО к игре внутри .cf-themed.
   * Движок не гарантирует стабильность селекторов между версиями: этот слой —
   * на совести мастера. Разумный предел настройки — токены и рамка выше;
   * голый CSS нужен редко.
   */
  custom_css?: string
}
